/**
 * Aerolift — apex to www redirect.
 *
 * WHY THIS IS CODE AND NOT A DASHBOARD RULE
 * -----------------------------------------
 * `_redirects` cannot do it: Cloudflare matches that file on path only and
 * explicitly does not support domain-level sources. A dashboard Single Redirect
 * can do it, but it lives outside the repo, cannot be reviewed in a diff, and
 * silently did nothing when we tried it. This is version-controlled and
 * testable with `wrangler dev`.
 *
 * WHY IT DOES NOT COST THE SECURITY HEADERS
 * -----------------------------------------
 * Cloudflare's docs state that `_headers` rules "are not applied to responses
 * generated by your Worker code, even if the request URL matches a rule defined
 * in `_headers`". Measured against `wrangler dev`, that is not true of responses
 * *proxied* from the assets binding: a response returned straight from
 * `env.ASSETS.fetch()` arrives with the full `_headers` set — CSP, HSTS,
 * Permissions-Policy, Referrer-Policy, X-Frame-Options, X-Content-Type-Options
 * and the right Cache-Control.
 *
 * The distinction that matters: do not BUILD a response here. Pass the asset
 * response through untouched. If a future change starts constructing responses
 * (`new Response(...)`) or rewriting bodies, re-verify the headers — that is
 * the case the documentation is warning about, and it would strip the CSP from
 * every page without any visible error.
 */

const APEX = 'aerolift-cranes.com';
const CANONICAL_HOST = 'www.aerolift-cranes.com';

export default {
  async fetch(request, env) {
    const url = new URL(request.url);

    if (url.hostname === APEX) {
      url.hostname = CANONICAL_HOST;
      // Force https rather than inheriting the request's scheme, so a plain
      // http:// hit lands on the final URL in one hop instead of being handed
      // to the http->https redirect for a second round trip.
      url.protocol = 'https:';
      // url.toString() carries the path and query already, so a bookmarked
      // /products/eot-cranes/?utm_source=... survives the move intact.
      return Response.redirect(url.toString(), 301);
    }

    // The quote form has no backend by design (see quote-form.html), so with
    // JavaScript enabled it never POSTs anywhere. Without JavaScript the browser
    // does submit natively, and a POST to a static asset returns 405 — a dead
    // end for someone who just typed out an enquiry. Send them back to the page
    // as a GET so they at least land on the phone number and email address.
    // 303 rather than 301/302: it is defined to convert the follow-up to GET.
    if (request.method === 'POST') {
      return new Response(null, { status: 303, headers: { Location: url.pathname } });
    }

    const response = await env.ASSETS.fetch(request);

    // `html_handling: "auto-trailing-slash"` sends /about -> /about/ as a 307
    // Temporary. Every canonical tag, internal link and sitemap entry on this
    // site uses the trailing-slash form, so that move is permanent and should
    // say so: a 301 consolidates the two URLs, a 307 asks crawlers to keep
    // checking the old one forever.
    //
    // Re-emitting the status is safe to construct by hand — a redirect carries
    // no body for the CSP to protect, and Location is the only header that
    // matters. Guarded to GET/HEAD so a 307's method-preserving guarantee is
    // never traded away on a request that has a body.
    if (
      (response.status === 307 || response.status === 308) &&
      response.headers.has('location') &&
      (request.method === 'GET' || request.method === 'HEAD')
    ) {
      return new Response(null, {
        status: 301,
        headers: { Location: response.headers.get('location') },
      });
    }

    // Everything else: hand straight back to the asset server, untouched, so
    // the _headers rules survive. See the note above about proxying vs building.
    return response;
  },
};
